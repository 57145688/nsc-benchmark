"""Post-process the OpenFOAM case: ring temperatures and densities.

The mesh is generated by ``build_foam_case.py`` as a single structured block,
so cell centres follow directly from the block indexing and do not need a
``writeCellCentres`` function object (which is unreliable in the packaged
OpenFOAM build used here).
"""

import argparse
import json
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from scripts import build_foam_case as case  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RINGS = [0.15, 0.35, 0.55, 0.85]
CORE_Z = (0.2, 2.4)
NR = 90
NZ = 300


def latest_time(case_dir):
    times = []
    for name in os.listdir(case_dir):
        try:
            times.append((float(name), name))
        except ValueError:
            continue
    if not times:
        raise FileNotFoundError(f"no time directories in {case_dir}")
    return max(times)[1]


def read_field(case_dir, time, name):
    path = os.path.join(case_dir, time, name)
    with open(path) as handle:
        text = handle.read()
    text = re.sub(r"//.*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    match = re.search(
        r"internalField\s+(?:nonuniform\s+)?List<(\w+)>\s*(\d+)\s*\(", text
    )
    if match:
        kind = match.group(1)
        count = int(match.group(2))
        start = match.end()
        end = text.index(";", start)
        body = text[start:end].replace("(", " ").replace(")", " ").split()
        values = np.array([float(token) for token in body])
        if kind == "vector":
            values = values.reshape(count, 3)
        else:
            values = values.reshape(count)
        return values
    uniform = re.search(r"internalField\s+uniform\s+([^;]+);", text)
    if not uniform:
        raise ValueError(f"cannot parse internalField in {path}")
    value = uniform.group(1).strip()
    if value.startswith("("):
        return np.array([[float(v) for v in value.strip("()").split()]])
    return np.array([float(value)])


def cell_centres():
    index = np.arange(NR * NZ)
    i = index % NR
    k = index // NR
    radius = case.R0 + (case.R_RPV - case.R0) * (i + 0.5) / NR
    z = case.Z_BOTTOM + (case.Z_TOP - case.Z_BOTTOM) * (k + 0.5) / NZ
    angle = 0.0
    return np.column_stack(
        [radius * np.cos(angle), radius * np.sin(angle), z]
    )


def ring_average(radius, values, radii, z_range, z):
    mask = (z >= z_range[0]) & (z <= z_range[1])
    result = {}
    for ring_index, outer in enumerate(radii, start=1):
        inner = 0.0 if ring_index == 1 else radii[ring_index - 2]
        selection = mask & (radius >= inner) & (radius < outer)
        if selection.any():
            result[ring_index] = {
                "temperature_K": float(values[selection].mean()),
                "cells": int(selection.sum()),
            }
    return result


# IAPWS-IF97 liquid water density at 15.5 MPa (kg/m3), sampled every 10 K.
# Below 450 K / above 610 K the table is clamped: near 618 K the fluid would be
# at saturation and the single-phase model no longer applies.
WATER_DENSITY = {
    450: 899.58,
    460: 889.21,
    470: 878.37,
    480: 867.05,
    490: 855.21,
    500: 842.79,
    510: 829.75,
    520: 816.02,
    530: 801.52,
    540: 786.12,
    550: 769.70,
    560: 752.05,
    570: 732.91,
    580: 711.87,
    590: 688.30,
    600: 661.12,
    610: 628.23,
}


def density_kg_m3(temperature):
    """Liquid density at 15.5 MPa from an IAPWS-IF97 table."""
    low, high = min(WATER_DENSITY), max(WATER_DENSITY)
    temperature = min(max(temperature, low), high)
    lower = int(temperature // 10 * 10)
    upper = min(lower + 10, high)
    fraction = (temperature - lower) / (upper - lower)
    return WATER_DENSITY[lower] + fraction * (
        WATER_DENSITY[upper] - WATER_DENSITY[lower]
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", default=os.path.join(HERE, "results", "foam", "case"))
    parser.add_argument("--time", default=None)
    parser.add_argument("--out", default=None)
    args = parser.parse_args(argv)

    case_dir = os.path.abspath(args.case)
    time = args.time or latest_time(case_dir)
    temperature = read_field(case_dir, time, "T")
    velocity = read_field(case_dir, time, "U")
    centres = cell_centres()
    if len(temperature) != len(centres):
        raise ValueError(
            f"mesh has {len(centres)} cells but T has {len(temperature)} values"
        )

    radius = np.hypot(centres[:, 0], centres[:, 1])
    z = centres[:, 2]
    rings = ring_average(radius, temperature, RINGS, CORE_Z, z)
    for index, data in rings.items():
        data["density_g_cm3"] = density_kg_m3(data["temperature_K"]) / 1000.0

    core = (z >= CORE_Z[0]) & (z <= CORE_Z[1]) & (radius < case.CORE_RADIUS)
    downcomer = (
        (z >= 0.0)
        & (z <= case.SG_Z[0])
        & (radius > case.DOWNCOMER_RADII[0])
        & (radius < case.DOWNCOMER_RADII[1])
    )
    downcomer_temperature = float(temperature[downcomer].mean())
    report = {
        "case": case_dir,
        "time": time,
        "temperature_min_K": float(temperature.min()),
        "temperature_max_K": float(temperature.max()),
        "temperature_mean_K": float(temperature.mean()),
        "core_mean_velocity_z_m_s": float(velocity[core, 2].mean()),
        "downcomer_mean_velocity_z_m_s": float(velocity[downcomer, 2].mean()),
        "downcomer_temperature_K": downcomer_temperature,
        "downcomer_density_g_cm3": density_kg_m3(downcomer_temperature) / 1000.0,
        "rings": rings,
    }
    output = args.out or os.path.join(
        HERE, "results", "coupling", f"foam_{time}.json"
    )
    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w") as handle:
        json.dump(report, handle, indent=2)
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
